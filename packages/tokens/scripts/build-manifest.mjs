#!/usr/bin/env node
// Build typed token manifest from dist/index.css.
// Outputs:
//   dist/manifest.json         — full structured data (for tooling)
//   dist/manifest-full.js      — full ESM (re-exports the JSON + helpers)
//   dist/manifest-runtime.js   — slim ESM: reverse map + tierByName only
//   dist/manifest.d.ts         — types for both subpaths

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parseCss, buildManifest, buildReverseMap } from './manifest-lib.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, '..');
const SRC_CSS = path.join(PKG_ROOT, 'dist', 'index.css');
const OUT_JSON = path.join(PKG_ROOT, 'dist', 'manifest.json');
const OUT_FULL_JS = path.join(PKG_ROOT, 'dist', 'manifest-full.js');
const OUT_RUNTIME_JS = path.join(PKG_ROOT, 'dist', 'manifest-runtime.js');
const OUT_DTS = path.join(PKG_ROOT, 'dist', 'manifest.d.ts');

const css = fs.readFileSync(SRC_CSS, 'utf-8');
const parsed = parseCss(css);
const manifest = buildManifest(parsed);
const reverseMap = buildReverseMap(manifest.entries);

// Stable order for deterministic diffs.
const reverseMapEntries = Array.from(reverseMap.entries()).sort(([a], [b]) =>
  a.localeCompare(b)
);
const tierByName = Object.fromEntries(
  manifest.entries.map((e) => [e.name, e.tier]).sort(([a], [b]) => a.localeCompare(b))
);

// ---------------------------------------------------------------------------
// Full manifest: complete data (~800 KB unminified, includes per-theme bindings).
// Consumed by tooling that needs varChain, raw declarations, theme bindings.
// ---------------------------------------------------------------------------

const fullJson = {
  hash: manifest.hash,
  themes: manifest.themes,
  entries: manifest.entries,
  reverseMap: reverseMapEntries,
};
fs.writeFileSync(OUT_JSON, JSON.stringify(fullJson, null, 2) + '\n');

const fullJsBody = `// Auto-generated by @cognivo/tokens/scripts/build-manifest.mjs.
// Do not edit by hand. Source: dist/index.css.

const data = ${JSON.stringify(fullJson, null, 0)};

export const manifestHash = data.hash;
export const themes = data.themes;
export const tokenManifest = Object.freeze(data.entries);
export const tokenByName = new Map(data.entries.map((e) => [e.name, e]));
export const tokensByValue = new Map(data.reverseMap);

export default tokenManifest;
`;
fs.writeFileSync(OUT_FULL_JS, fullJsBody);

// ---------------------------------------------------------------------------
// Runtime manifest: slim payload for in-page audit (reverse map + tiers only).
// This is what @cognivo/lens-core imports. Goal: under 100 KB unminified.
// ---------------------------------------------------------------------------

const runtimeData = {
  hash: manifest.hash,
  reverseMap: reverseMapEntries,
  tierByName,
};
const runtimeJsBody = `// Auto-generated by @cognivo/tokens/scripts/build-manifest.mjs.
// Slim runtime payload — reverse-lookup + tier classification only.
// Tooling needing full token data should import @cognivo/tokens/manifest.

const data = ${JSON.stringify(runtimeData, null, 0)};

export const manifestHash = data.hash;
export const tokensByValue = new Map(data.reverseMap);
export const tierByName = new Map(Object.entries(data.tierByName));
`;
fs.writeFileSync(OUT_RUNTIME_JS, runtimeJsBody);

// ---------------------------------------------------------------------------
// Shared types
// ---------------------------------------------------------------------------

const dtsBody = `// Auto-generated by @cognivo/tokens/scripts/build-manifest.mjs.
// Do not edit by hand.

export type TokenTier = 1 | 2 | 3;

export type TokenCategory =
  | 'color'
  | 'numeric'
  | 'compound'
  | 'easing'
  | 'keyword';

export interface TokenThemeBinding {
  /** Original CSS value, including any var() references. */
  rawDeclaration: string;
  /** Fully resolved value. Colors are normalized to canonical rgb()/rgba(). */
  resolvedValue: string;
  /** [self, intermediate, ..., leaf]. Length 1 means the value is a literal. */
  varChain: string[];
}

export interface TokenEntry {
  /** Full custom-property name including the leading "--". */
  name: string;
  /** Tier 1 = primitives + palette, 2 = semantic, 3 = component-scoped. */
  tier: TokenTier;
  /** Category derived from the resolved value's syntactic shape. */
  category: TokenCategory;
  /** Per-theme value bindings. Always at least one (\`default\`). */
  themes: Record<string, TokenThemeBinding>;
}

/** Stable content hash of all entries. Use to invalidate downstream caches. */
export const manifestHash: string;

/**
 * Reverse map: normalized resolved value → token names that produce it.
 * Buckets are sorted by tier ascending, then by name length descending
 * (most specific name first within a tier).
 */
export const tokensByValue: ReadonlyMap<string, readonly string[]>;

/** O(1) tier lookup. Always populated for every token in the manifest. */
export const tierByName: ReadonlyMap<string, TokenTier>;

// --- @cognivo/tokens/manifest only (full export) ---

/** Theme names declared in the source CSS, in source order. */
export const themes: readonly string[];

/** All tokens, sorted by tier ascending then by name. */
export const tokenManifest: readonly TokenEntry[];

/** O(1) lookup by token name. */
export const tokenByName: ReadonlyMap<string, TokenEntry>;

/** Convenience default export = tokenManifest. */
declare const _default: typeof tokenManifest;
export default _default;
`;
fs.writeFileSync(OUT_DTS, dtsBody);

const sizes = [
  [path.relative(PKG_ROOT, OUT_JSON), fs.statSync(OUT_JSON).size],
  [path.relative(PKG_ROOT, OUT_FULL_JS), fs.statSync(OUT_FULL_JS).size],
  [path.relative(PKG_ROOT, OUT_RUNTIME_JS), fs.statSync(OUT_RUNTIME_JS).size],
  [path.relative(PKG_ROOT, OUT_DTS), fs.statSync(OUT_DTS).size],
];

console.log(`[build-manifest] hash=${manifest.hash}`);
console.log(`[build-manifest] entries=${manifest.entries.length}`);
console.log(`[build-manifest] themes=${manifest.themes.join(', ')}`);
console.log(`[build-manifest] reverse-map buckets=${reverseMap.size}`);
for (const [rel, size] of sizes) {
  console.log(`[build-manifest] ${rel}: ${(size / 1024).toFixed(1)} KB`);
}
